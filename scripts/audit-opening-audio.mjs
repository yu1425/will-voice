// Targeted verification of the canonical opening through native browser media.
import assert from "node:assert/strict";
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
const { chromium } = await import(process.env.WILL_PLAYWRIGHT_MODULE ?? "playwright");
const base = process.env.WILL_AUDIT_URL ?? "http://127.0.0.1:3002";
const reportPath = process.env.WILL_OPENING_REPORT ?? "reports/flow-opening-browser-audit.json";
const source = JSON.parse(readFileSync("lib/flowScripts.json", "utf8"))[0].variants[0];
const audit = JSON.parse(readFileSync("reports/flow-audio-v2-audit.json", "utf8"))
  .files.find((file) => file.id === "opening");
const expectedHash = createHash("sha256").update(readFileSync("public" + source.audioSrc)).digest("hex");
const browser = await chromium.launch({ headless: true });
const context = await browser.newContext({ viewport: { width: 390, height: 844 } });
const page = await context.newPage();
const errors = [];
const checks = [];
page.on("pageerror", (error) => errors.push(error.message));
const pass = (name, evidence) => {
  checks.push({ name, pass: true, evidence });
  console.log("PASS " + name);
};
await context.addInitScript(() => {
  window.__media = [];
  window.__speechCalls = 0;
  const AudioCtor = window.Audio;
  window.Audio = function (...args) {
    const audio = new AudioCtor(...args);
    window.__media.push(audio);
    return audio;
  };
  window.Audio.prototype = AudioCtor.prototype;
  const speak = speechSynthesis.speak.bind(speechSynthesis);
  speechSynthesis.speak = (...args) => {
    window.__speechCalls++;
    return speak(...args);
  };
});
const button = (name) => page.getByRole("button", { name: name === "もう一度聞く" ? /^(案内を聞く|もう一度聞く)$/ : name, exact: true });
const playing = () => page.waitForFunction(() => window.__media.some((audio) =>
  audio.src.endsWith("00-opening.wav") && !audio.paused && audio.currentTime > 0.5));
const mediaState = () => page.evaluate(() => {
  const audio = window.__media.findLast((audio) => audio.src.endsWith("00-opening.wav") && audio.currentTime > 0);
  return { src: audio.src, currentTime: audio.currentTime, duration: audio.duration, paused: audio.paused, ended: audio.ended, volume: audio.volume };
});
try {
  assert.equal(source.displayText, audit.displayText);
  assert.ok(source.displayText.replace(/\s/g, "").startsWith("本日はご参加ありがとうございます。まずは近くの方とペアを作って、ショートラリーから始めてください。"));
  assert.ok(!source.displayText.includes("これからWILL.tennisを始めます"));
  pass("canonical display and VOICEVOX audit agree; removed sentence absent");
  const response = await context.request.get(base + source.audioSrc);
  assert.equal(response.status(), 200);
  assert.equal(createHash("sha256").update(await response.body()).digest("hex"), expectedHash);
  pass("served opening WAV matches regenerated bytes", { sha256: expectedHash });
  await page.goto(base + "/flow");
  await button("自動進行を開始").click();
  await playing();
  const decoded = await page.evaluate(async (src) => {
    const audioContext = new AudioContext();
    try {
      const buffer = await audioContext.decodeAudioData(await (await fetch(src)).arrayBuffer());
      return { duration: buffer.duration, channels: buffer.numberOfChannels, sampleRate: buffer.sampleRate };
    } finally { await audioContext.close(); }
  }, source.audioSrc);
  assert.ok(Math.abs(decoded.duration - audit.durationSec) < 0.01);
  pass("real AudioContext decodes the regenerated opening", decoded);
  await page.waitForFunction(() => window.__media.some((audio) =>
    audio.src.endsWith("00-opening.wav") && audio.ended), null, { timeout: 45000 });
  pass("automatic opening plays through to native ended under default autoplay policy", await mediaState());
  await button("もう一度聞く").click();
  await playing();
  await button("今の音声を止める").click();
  assert.equal(await page.evaluate(() => window.__media.filter((audio) => !audio.paused).length), 0);
  pass("replay uses opening WAV and current-audio stop cancels it");
  await page.locator(".flow-session-settings > summary").click();
  await button("自動進行を終了").click();
  await button("終了する").click();
  await button("個別進行").click();
  await button("全文を見る").click();
  assert.ok((await page.locator("body").innerText()).includes(source.displayText.split("\n\n")[1]));
  assert.ok(!(await page.locator("body").innerText()).includes("これからWILL.tennisを始めます"));
  await button("もう一度聞く").click();
  await playing();
  const manual = await mediaState();
  assert.ok(Math.abs(manual.duration - audit.durationSec) < 0.01);
  pass("manual STEP 1 displays revised script and plays the same regenerated WAV", manual);
  await page.screenshot({ path: "reports/flow-opening-manual-390.png", fullPage: true });
  assert.equal(await page.evaluate(() => window.__speechCalls), 0);
  assert.deepEqual(errors, []);
  pass("zero SpeechSynthesis fallback and zero runtime errors");
  writeFileSync(reportPath, JSON.stringify({ auditedAt: new Date().toISOString(), base, method: "Real Chromium, native HTMLAudioElement and AudioContext, default autoplay policy, no media mocks", checks, errors }, null, 2) + "\n");
} finally {
  await context.close();
  await browser.close();
}
